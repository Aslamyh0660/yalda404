// node scripts/fonts.mjs   (npm run fonts)
//
// Self-hosts the site's WOFF2 fonts: copies the subsets this page needs out of
// the @fontsource packages into public/fonts/ and writes src/styles/fonts.css.
//
// The @font-face rules are written here rather than imported from
// @fontsource/<family>/<subset>-<weight>.css, because those subset files carry
// no `unicode-range`: with Arabic and Latin files declaring the same family and
// weight, the last rule would win for every character and the Latin handle,
// wordmark and numbers would fall back to a system font. Each file gets the
// Google Fonts range for its subset instead, so the browser downloads the
// Arabic file for Arabic and the Latin file for Latin.
//
// Arabic shaping (initial / medial / final forms, lam-alef ligatures, marks) is
// inside the font files and untouched by subsetting: only the glyph set is
// limited, never the OpenType layout tables.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")

/** Google Fonts unicode ranges, per subset */
const RANGE = {
  arabic:
    "U+0600-06FF, U+0750-077F, U+0870-088E, U+0890-0891, U+0897-08E1, " +
    "U+08E3-08FF, U+200C-200E, U+2010-2011, U+204F, U+2E41, U+FB50-FDFF, " +
    "U+FE70-FE74, U+FE76-FEFC, U+102E0-102FB, U+10E60-10E7E, U+1EE00-1EEFF",
  latin:
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, " +
    "U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, " +
    "U+2212, U+2215, U+FEFF, U+FFFD",
}

/**
 * family → the subsets and weights this page uses.
 * Keep the list short: every file here is a download a visitor pays for.
 */
const FONTS = [
  {
    pkg: "@fontsource/ibm-plex-sans-arabic",
    family: "IBM Plex Sans Arabic",
    comment: "Arabic body and UI text (OFL, IBM)",
    files: [
      ["arabic", 400],
      ["arabic", 500],
      ["arabic", 600],
      ["latin", 400],
      ["latin", 600],
    ],
  },
  {
    pkg: "@fontsource/noto-kufi-arabic",
    family: "Noto Kufi Arabic",
    comment: "Arabic headings and the slogan (OFL, Google Noto)",
    files: [
      ["arabic", 500],
      ["arabic", 600],
    ],
  },
  {
    pkg: "@fontsource/cormorant-garamond",
    family: "Cormorant Garamond",
    comment: "the SHAREA Latin wordmark only (OFL, Catharsis Fonts)",
    files: [["latin", 600]],
  },
]

let out = `/*
 * Self-hosted WOFF2 — generated by scripts/fonts.mjs (npm run fonts).
 * font-display: swap, one unicode-range per subset, so a visitor downloads only
 * the Arabic or the Latin file the page actually needs.
 *
 * The two files the first screen needs are preloaded in index.html.
 */\n`
let total = 0
let copied = 0

for (const font of FONTS) {
  const pkgRoot = join(root, "node_modules", font.pkg)
  const pkgName = font.pkg.split("/").pop()
  out += `\n/* ${font.family} — ${font.comment} */\n`
  for (const [subset, weight] of font.files) {
    const file = `${pkgName}-${subset}-${weight}-normal.woff2`
    const from = join(pkgRoot, "files", file)
    if (!existsSync(from)) {
      console.error(`missing ${from} — is ${font.pkg} installed?`)
      process.exitCode = 1
      continue
    }
    mkdirSync(join(root, "public", "fonts"), { recursive: true })
    copyFileSync(from, join(root, "public", "fonts", file))
    total += readFileSync(from).length
    copied += 1
    out += `@font-face {
  font-family: "${font.family}";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("/fonts/${file}") format("woff2");
  unicode-range: ${RANGE[subset]};
}\n`
  }
}

mkdirSync(join(root, "src", "styles"), { recursive: true })
writeFileSync(join(root, "src", "styles", "fonts.css"), out)
console.log(
  `wrote src/styles/fonts.css and public/fonts/ — ${copied} files, ${(total / 1024).toFixed(0)} KB`
)
